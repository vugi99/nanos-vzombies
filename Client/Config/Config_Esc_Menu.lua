# 🧟 VZombies
*The classic round-based cooperative zombie survival experience.*

Welcome to **VZombies**! Team up with fellow survivors (or smart AI companions) to battle relentless undead waves. Earn points, unlock quarantine zones, buy wall weapons, gamble at the Mystery Box, drink Perk Colas, and Pack-a-Punch your weapons to survive the horde.

---

## 🎮 Controls & Keybinds
* **Move:** `W` `A` `S` `D` | **Sprint:** `Shift` | **Jump:** `Space` | **Crouch:** `C` / `Ctrl`
* **Combat:** `Left Click` to shoot, `Right Click` to ADS (Aim Down Sights), `R` to reload
* **Melee & Equipment:** `V` to Knife, `G` to throw Grenade
* **Interact (`E`):** Hold or press `E` to:
  * Open doors and clear debris barricades
  * Buy wall weapons and refill ammo
  * Spin the Mystery Box
  * Purchase and drink Perk Colas
  * Turn on map Power and use the Pack-a-Punch machine
  * Rebuild window barricades
  * Revive fallen teammates before they bleed out
* **Utilities:**
  * `F` - 3D Ping (highlight threats, weapons, objectives)
  * `Tab` - Scoreboard & match stats
  * `H` - In-game How to Play guide
  * `O` - Player Settings
  * `B` - Bot Orders radial menu (direct companion bots)
  * `P` - Pause game (Host only)

---

## 📖 How to Play & Survival Strategy
* **Survive the Waves:** Eliminate all zombies to advance. Every round brings faster, tougher, and more dangerous enemies. If everyone is downed, the match ends!
* **Earn Cash:** Gain points for hits, lethal headshots, knife kills, and reviving teammates. Avoid going down, as you lose points upon bleedout or death!
* **Open the Map:** Spend points to open debris and locked doors to reach the Power Switch, perk machines, and defensive choke points.
* **Turn on the Power:** Activating the main power switch is vital to power up Perk machines, Pack-a-Punch, Wunderfizz, and teleporters.
* **Stick Together:** Teamwork is key! Watch each other's backs and revive downed teammates.

---

## 🥤 Perk-a-Cola Vending Machines
* **Juggernog:** Increases max health from 100 to 250 HP.
* **Quick Revive:** Cuts revive times in half; grants self-revive in solo play.
* **Speed Cola:** Greatly speeds up weapon reloading and handling.
* **Double Tap:** Increases fire rate and bullet damage.
* **Stamin-Up:** Boosts movement speed and sprint duration.
* **Three Gun:** Allows you to carry a third weapon.
* **Der Wunderfizz:** Dispenses a random perk concoction.

---

## 💥 Tactical Powerups
* 💀 **Insta-Kill:** All zombie damage is instantly lethal for 30 seconds.
* 📦 **Max Ammo:** Instantly refills ammunition and grenades for all players.
* 💣 **Nuke:** Obliterates all current zombies on the map and awards bonus cash.
* 🔨 **Carpenter:** Instantly repairs all window barricades across the map + bonus cash.
* 💰 **Double Points (x2):** Multiplies all point gains by 2 for a limited time.
* 🚀 **Death Machine:** Grants a heavy minigun with devastating firepower.

---

## ⚡ Arsenal & Upgrades
* **Wall Buys:** Purchase chalk weapons off walls and restock ammo between rounds.
* **Mystery Box:** Gamble for high-tier weaponry and coveted Wonder Weapons like the Raygun!
* **Pack-a-Punch:** Upgrades weapon damage, magazine capacity, and appearance. Re-pack to unlock elemental ammo types (Blast Furnace, Electric).

---

